"""Legacy Ingest-Proposal export journey (G4, spec 0008 §7, AC5).

One coherent migration journey over a synthetic legacy store whose bytes,
identities, digests, and transition intent are INDEPENDENTLY authored in
``tests/fixtures/legacy_ingest/`` (the original persisted wire format; never
generated by the exporter). Expected pages, hashes, and bindings derive from
those fixture bytes and spec AC5 — not from exporter output.

Coverage: read-only inventory; preview that creates nothing; a confirmed
export to an UNADMITTED Git branch on an explicit baseline; preservation of
the original store/raw/history bytes; an unchanged published pointer; an
idempotent matching retry; an edited-destination conflict; and a stale
binding variant that refuses without data loss. The registry's native-writer
refusal over unresolved legacy pending state is pinned here too.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
from pathlib import Path

import pytest
from lumio_wiki.legacy_proposals import (
    LegacyExportBlockedError,
    LegacyExportConflictError,
    export_legacy_proposal,
    inventory_legacy_store,
    plan_legacy_export,
)
from lumio_wiki.source_registry import SourceRegistry, SourceRegistryError

ROOT = Path(__file__).parents[3]
FIXTURES = ROOT / "tests" / "fixtures" / "legacy_ingest"

BASELINE_PAGE = """---
id: "entity:export-fixture"
title: "Export Fixture Entity"
entity_types:
  - fact
tags:
  - "fixture"
summary: "Export fixture entity."
lifecycle: "approved"
visibility: "public"
sources:
  - id: "manual-src"
    title: "Retired Manual"
  - id: "other-src"
    title: "Other Source"
---

Body that mentions [[Export Fixture Entity]] internally.
"""

BASELINE_CONTROL = """\
version: 2
mode: "categorized"
categories:
  - name: entities
ontology:
  entity_types:
    fact: {}
  predicates: {}
  redirects: {}
"""


def _git(root: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(root), *args], capture_output=True, text=True, check=True
    )
    return result.stdout.strip()


def _baseline_repo(tmp_path: Path) -> tuple[Path, str]:
    """A committed baseline KB whose page declares the legacy source ids."""
    repo = tmp_path / "repo"
    (repo / "kb" / "entities").mkdir(parents=True)
    _git(repo, "init", "-q")
    _git(repo, "config", "user.email", "t@example.com")
    _git(repo, "config", "user.name", "T")
    (repo / "kb" / ".lumio-authoring.yaml").write_text(
        "version: 1\nnamespace: legacy-fixture-kb\nsources:\n"
        "  manual-src:\n    status: retired\nbindings: {}\n",
        encoding="utf-8",
    )
    (repo / "kb" / "lumio.yaml").write_text(BASELINE_CONTROL, encoding="utf-8")
    (repo / "kb" / "entities" / "export-fixture.md").write_text(BASELINE_PAGE, encoding="utf-8")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "baseline")
    return repo / "kb", _git(repo, "rev-parse", "HEAD")


def _store(tmp_path: Path) -> Path:
    """A disposable copy of the synthetic legacy store."""
    root = tmp_path / "legacy-store"
    shutil.copytree(FIXTURES, root)
    return root


def _fixture_digests() -> tuple[str, str]:
    """Independent oracle: the exact digests of the fixture bytes."""
    raw = (FIXTURES / "raw" / "exportme0001" / "manual.txt").read_bytes()
    record = (FIXTURES / "proposals" / "exportme0001.json").read_bytes()
    return hashlib.sha256(raw).hexdigest(), hashlib.sha256(record).hexdigest()


def _tree_state(root: Path, *, include_receipts: bool = False) -> dict[str, bytes | None]:
    """Original store bytes; the private migration receipt is an authorized
    addition and is excluded unless explicitly requested."""
    return {
        str(path.relative_to(root)): path.read_bytes() if path.is_file() else None
        for path in sorted(root.rglob("*"))
        if include_receipts or path.relative_to(root).parts[0] != "migration-receipts"
    }


def test_export_journey(tmp_path: Path):
    kb_path, baseline = _baseline_repo(tmp_path)
    store = _store(tmp_path)
    published = tmp_path / "published"
    published.mkdir()
    pointer = published / "current.json"
    pointer.write_bytes(b'{"version":"prior-complete"}\n')
    pointer_before = pointer.read_bytes()
    preview_before = _tree_state(tmp_path, include_receipts=True)
    raw_digest, record_digest = _fixture_digests()
    authored_markdown = json.loads((store / "proposals" / "exportme0001.json").read_text())[
        "proposed_pages"
    ][0]["markdown"]
    before = _tree_state(store)

    # 1) Read-only inventory: classification and pending transition, and the
    #    preview creates NOTHING (no directories, receipts, refs, worktrees).
    absent = tmp_path / "absent-private-store"
    assert not inventory_legacy_store(absent).store_exists
    assert not absent.exists()
    inventory = inventory_legacy_store(store)
    assert inventory.store_exists
    assert inventory.source_versions == (
        (
            "manual-src",
            "retired",
            "b5679b404c4f7001be5e6c681eea853015c65940e4c28aedf23de9eb2f94437a",
        ),
    )
    assert [r.proposal_id for r in inventory.unreviewed] == ["exportme0001", "orphan0002"]
    assert inventory.terminal == () and inventory.undecodable == ()
    assert [(p.action, p.source_id) for p in inventory.pending_transitions] == [
        ("reactivate", "manual-src")
    ]
    record = next(r for r in inventory.records if r.proposal_id == "exportme0001")
    assert record.raw_file_count == 1 and record.source_action == "reactivate"
    assert _tree_state(store) == before
    assert not list((tmp_path / "repo" / ".git" / "refs" / "heads").glob("legacy/*"))

    # 2) Preview plan: representable intent, exact digest from the pending
    #    transition (never registry-latest), and still zero side effects.
    plan = plan_legacy_export(
        store, "exportme0001", kb_root=kb_path, baseline="HEAD", branch="legacy/export-a"
    )
    assert plan.baseline == baseline
    with pytest.raises(LegacyExportBlockedError, match="captured FULL baseline"):
        export_legacy_proposal(
            store, "exportme0001", kb_root=kb_path, baseline="HEAD", branch="legacy/export-a"
        )
    assert plan.blocking_diagnostics == ()
    assert plan.binding_sha256 == raw_digest
    assert plan.written_pages == ("entities/export-fixture.md",)
    assert plan.record_sha256 == record_digest
    assert _tree_state(store) == before
    assert _tree_state(tmp_path, include_receipts=True) == preview_before

    # 3) Confirmed export: an UNADMITTED branch based on the exact baseline.
    result = export_legacy_proposal(
        store, "exportme0001", kb_root=kb_path, baseline=baseline, branch="legacy/export-a"
    )
    assert result.recognized_retry is False
    assert result.commit != baseline
    assert _git(kb_path.parent, "merge-base", "--is-ancestor", baseline, result.commit) == ""
    # The baseline branch (HEAD) is untouched; no Published Version exists.
    assert _git(kb_path.parent, "rev-parse", "HEAD") == baseline
    assert not list(kb_path.rglob("versions"))
    # The exported page carries the record's authored bytes; the manifest
    # declares the reactivated source ACTIVE with the exact fixture digest.
    branch_root = _git(kb_path.parent, "rev-parse", "legacy/export-a")
    page = _git(kb_path.parent, "show", f"{branch_root}:kb/entities/export-fixture.md")
    assert authored_markdown.rstrip("\n") in page and page.rstrip("\n").endswith(
        authored_markdown.rstrip("\n")
    )
    manifest = _git(kb_path.parent, "show", f"{branch_root}:kb/.lumio-authoring.yaml")
    import msgspec.yaml

    refs = msgspec.yaml.decode(manifest)
    assert refs["namespace"] == "legacy-fixture-kb"
    assert refs["sources"]["manual-src"]["status"] == "active"
    assert refs["bindings"] == {"entity:export-fixture": {"manual-src": raw_digest}}
    assert pointer.read_bytes() == pointer_before
    # No private filename, key, or path entered the Git content.
    assert "manual.txt" not in page and "legacy-store" not in page

    # 4) The original store, raw bytes, and private history are preserved;
    #    the only addition is the private idempotent migration receipt,
    #    which binds the record digest to the exported branch/commit.
    assert _tree_state(store) == before
    receipt_state = _tree_state(store, include_receipts=True)
    receipt = json.loads(receipt_state["migration-receipts/exportme0001.json"])
    assert receipt["record_sha256"] == record_digest
    assert receipt["branch"] == "legacy/export-a" and receipt["commit"] == result.commit
    assert receipt["baseline"] == baseline

    # 5) A matching retry is recognized: same commit, no duplicate changes.
    retry = export_legacy_proposal(
        store, "exportme0001", kb_root=kb_path, baseline=baseline, branch="legacy/export-a"
    )
    assert retry.recognized_retry is True and retry.commit == result.commit

    # 6) An edited destination conflicts; nothing is overwritten.
    _git(kb_path.parent, "checkout", "-q", "legacy/export-a")
    (kb_path / "entities" / "export-fixture.md").write_text(
        authored_markdown.replace("Body refreshed", "Body edited by an operator"),
        encoding="utf-8",
    )
    _git(kb_path.parent, "add", "-A")
    _git(kb_path.parent, "commit", "-qm", "operator edit on the export branch")
    _git(kb_path.parent, "checkout", "-q", "-")
    edited_tip = _git(kb_path.parent, "rev-parse", "legacy/export-a")
    with pytest.raises(LegacyExportConflictError) as excinfo:
        export_legacy_proposal(
            store, "exportme0001", kb_root=kb_path, baseline=baseline, branch="legacy/export-a"
        )
    assert "refusing to overwrite or duplicate" in str(excinfo.value)
    assert _git(kb_path.parent, "rev-parse", "legacy/export-a") == edited_tip
    assert _tree_state(store) == before


def test_unknown_exact_binding_refuses_without_data_loss(tmp_path: Path):
    """A reactivation whose exact bound version is stale/unknown blocks.

    The record claims a reactivation but its proposal-keyed pending
    transition no longer exists, so no exact digest is representable and the
    registry is never consulted for a latest substitute (spec AC5). The
    record stays untouched and no branch exists afterwards.
    """
    kb_path, baseline = _baseline_repo(tmp_path)
    store = _store(tmp_path)
    before = _tree_state(store)

    plan = plan_legacy_export(
        store, "orphan0002", kb_root=kb_path, baseline=baseline, branch="legacy/export-b"
    )
    assert plan.blocking_diagnostics
    assert any("exact bound Source Version" in d for d in plan.blocking_diagnostics)
    assert plan.binding_sha256 is None
    with pytest.raises(LegacyExportBlockedError):
        export_legacy_proposal(
            store, "orphan0002", kb_root=kb_path, baseline=baseline, branch="legacy/export-b"
        )
    assert not (kb_path.parent / ".git" / "refs" / "heads" / "legacy").exists()
    assert _tree_state(store) == before


def test_native_registry_writer_refuses_unresolved_legacy_pending(tmp_path: Path):
    """A native registry write never silently ignores legacy pending state."""
    root = _store(tmp_path) / "source-registry"
    path = root / "sources.json"
    state = json.loads(path.read_bytes())
    state["sources"].append(
        {
            "source_id": "steady-src",
            "status": "active",
            "versions": [
                {
                    "source_id": "steady-src",
                    "content_hash": hashlib.sha256(b"same").hexdigest(),
                    "created_at": "2026-01-01T00:00:00Z",
                }
            ],
        }
    )
    path.write_text(json.dumps(state))
    before = path.read_bytes()
    registry = SourceRegistry(root)
    with pytest.raises(SourceRegistryError, match="legacy-proposals"):
        registry.register_source("another-source", b"bytes")
    with pytest.raises(SourceRegistryError, match="legacy-proposals"):
        registry.register_version("steady-src", b"same")
    assert path.read_bytes() == before
